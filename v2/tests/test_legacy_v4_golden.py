"""Replay pristine-base v1-v3 admission and training records byte-for-byte.

The expected JSON was generated by the detached pristine worktree at
1bc2cc6ce3c4e7e93f01baeca1dbc414f880ede1, never by this implementation.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from sn120_v2.admission import Invalid, check_batch, frozen_batch
from sn120_v2.canonical import canonical_json
from sn120_v2.gpu.batch import training_rows
from sn120_v2.params import Params
from sn120_v2.types import Registration

GOLDEN = Path(__file__).parent / "data" / "legacy_v1_v3_v4_golden.json"


class Tokens:
    def prompt_tokens(self, text):
        return len(text.split())

    def output_tokens(self, text):
        return len(text.split())


def grade(prompt, output, capped):
    return 1.0 if "\\boxed{1}" in output else 0.0


def batch_dict(batch):
    return {
        "format": batch.format,
        "groups": batch.groups,
        "train": batch.train,
        "checked": batch.checked,
        "train_token_steps": batch.train_token_steps,
        "n_prompts": batch.n_prompts,
        "n_rollouts": batch.n_rollouts,
    }


@pytest.mark.parametrize("case", json.loads(GOLDEN.read_text())["cases"], ids=lambda case: case["name"])
def test_pristine_legacy_records_are_byte_identical(case):
    raw, expected = case["raw"].encode(), case["expected"]
    params = Params(min_signal_rollouts=1, min_step_norm=0.0)
    if not expected["valid"]:
        with pytest.raises(Invalid) as caught:
            check_batch(raw, "5Legacy", params, tokens=Tokens(), grader=grade)
        assert caught.value.rule == expected["rule"]
        assert str(caught.value) == expected["reason"]
        return
    batch = check_batch(raw, "5Legacy", params, tokens=Tokens(), grader=grade)
    frozen = frozen_batch(batch, Registration(1, "5Legacy", 100, 1), "private/batch.json")
    recipe = params.recipe.for_miner(batch.train)
    job = {"base_dir": "/base", "base_hash": "b" * 64, "dtype": "float32",
           "recipe": recipe.to_dict(), "seed": 7, "rows": training_rows(batch.groups, recipe.group_size)}
    for actual, wanted in ((batch_dict(batch), expected["batch"]), (frozen.to_dict(), expected["frozen"]), (job, expected["job"])):
        assert canonical_json(actual) == canonical_json(wanted)
