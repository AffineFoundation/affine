"""Prospective complete-group coordinator, independent of continuous audits.

The host supplies its authenticated release, native tokenizer/taskset, bucket
and authority. This module never sets chain weights or changes public discovery.
Its private opening/dispatch records can be consumed by the normal role queue.
"""
from __future__ import annotations

import base64
from collections import Counter
import copy
import fcntl
import json
import os
from pathlib import Path
import secrets
import time

from .storage import canonical, sha
from .backend_jobs import signed
from .controller import save_manifest
from .complete_group_capture import AdmissionLedger, capture, _get, _immutable
from .complete_group_transport import capability
from .complete_group_admission import TaskAuthority
from .complete_group_native_receipts import compact_native_grades
from .batch_contract import for_manifest, REQUIRED_CLIENT_FEATURES, CompleteGroupContract

VERSION = 'mimo-complete-group-coordinator-v1'


def _need(value, why):
    if not value:
        raise ValueError(why)


def _signed(identity, value):
    return dict(payload=value, signer=identity.id,
                signature=base64.b64encode(identity.key.sign(canonical(value)).signature).decode())


class Coordinator:
    """One epoch namespace, restartable from the same signed opening.

    Structural capture and native grading do not wait for any sampling audit.
    A signed dispatch records assurance honestly as unaudited. Future auditors
    must use the exact captured commitment/document hashes.
    """
    def __init__(self, root, bucket, identity, *, resolve_task, grade_batch, release_policy=None, grade_batches=None):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        _need(not self.root.is_symlink(), 'ordinary private coordinator state')
        self.bucket, self.identity = bucket, identity
        self.resolve_task, self.grade_batch = resolve_task, grade_batch
        self.release_policy = release_policy
        self.grade_batches = grade_batches

    def _namespace(self, manifest):
        if self.release_policy is not None:
            self.release_policy.validate_manifest(manifest)
            return self.release_policy.namespace() + '/epochs/' + manifest['epoch']
        _need(manifest.get('payable') is False and
              manifest['epoch'].startswith(('private-', 'test-', 'nonpayable-')),
              'pre-cutover coordinator is private/nonpayable only')
        return 'private/' + manifest['epoch']

    def _lock(self):
        fd = os.open(self.root / 'coordinator.lock', os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BaseException:
            os.close(fd)
            raise
        return fd

    def opening(self):
        envelope = json.loads((self.root / 'OPENING.json').read_bytes())
        value = signed(envelope, self.identity.id)
        self._namespace(value)
        return envelope, value

    def open(self, manifest, miners):
        """Mint private epoch capabilities once. The caller opens discovery later."""
        fd = self._lock()
        try:
            miners = sorted(set(miners))
            _need(miners and len(miners) <= 256 and all(isinstance(k, str) and len(k) == 64 for k in miners),
                  'registered public miner identities')
            _need('capabilities' not in manifest, 'capabilities are generated by the coordinator')
            contract = for_manifest(manifest, supported_features=REQUIRED_CLIENT_FEATURES)
            _need(isinstance(contract, CompleteGroupContract), 'complete-group opening required')
            namespace = self._namespace(manifest)
            request = dict(manifest=manifest, miners=miners)
            request_path = self.root / 'OPENING-REQUEST.json'
            if request_path.exists():
                _need(json.loads(request_path.read_bytes()) == request, 'opening request cannot change on retry')
            else:
                save_manifest(request_path, request)
            if (self.root / 'OPENING.json').exists():
                envelope, value = self.opening()
                stripped = dict(value)
                stripped.pop('capabilities')
                _need(stripped == manifest and sorted(value['capabilities']) == miners, 'same original opening')
            else:
                value = copy.deepcopy(manifest)
                value['capabilities'] = {miner: capability(self.bucket, manifest, miner,
                    registered_miners=set(miners)) for miner in miners}
                envelope = _signed(self.identity, value)
                save_manifest(self.root / 'OPENING.json', envelope)
            _immutable(self.bucket, namespace + '/mimo/opening.json', canonical(envelope))
            return envelope
        finally:
            os.close(fd)

    def collect(self, miner, *, now=None):
        fd = self._lock()
        try:
            _need(not (self.root / 'POPULATION.json').exists() and
                  not (self.root / 'DISPATCH.json').exists(), 'epoch population already sealed')
            envelope, manifest = self.opening()
            _need(miner in manifest['capabilities'], 'registered epoch identity')
            result = capture(self.bucket, AdmissionLedger(self.root / 'admission.sqlite'),
                manifest, miner, registered_miners=set(manifest['capabilities']),
                resolve_task=self.resolve_task, now=now)
            record = _signed(self.identity, dict(version=VERSION, epoch=manifest['epoch'],
                manifest_sha256=sha(canonical(manifest)), miner=miner, **result))
            save_manifest(self.root / 'captured' / (miner + '.json'), record)
            return record
        finally:
            os.close(fd)

    def seal(self, *, max_tasks=512, now=None):
        """Freeze training selection once and grade compact inputs, without GPU audits.

        The epoch-wide random selection seed is generated after its deadline.
        Outcome claims from miners are never accepted as native grade evidence.
        Selection retains whole groups and at most one group per task.
        """
        fd = self._lock()
        try:
            _, manifest = self.opening()
            at = time.time() if now is None else now
            _need(at >= manifest['deadline'], 'training population cannot seal before the collection deadline')
            _need(type(max_tasks) is int and 1 <= max_tasks <= 512, 'bounded whole-task training selection')
            existing = self.root / 'DISPATCH.json'
            if existing.exists():
                result = json.loads(existing.read_bytes())
                payload = signed(result, self.identity.id)
                _need(payload['epoch'] == manifest['epoch'] and
                      payload['manifest_sha256'] == sha(canonical(manifest)) and
                      payload['selection']['max_tasks'] == max_tasks, 'same original finalized dispatch')
                return result
            prepared = self.root / 'PREPARED-DISPATCH.json'
            if prepared.exists():
                # A successful remote write with a lost acknowledgement must
                # retry its exact bytes, not regenerate native grades or scores.
                result = json.loads(prepared.read_bytes())
                payload = signed(result, self.identity.id)
                _need(payload['epoch'] == manifest['epoch'] and
                      payload['manifest_sha256'] == sha(canonical(manifest)) and
                      payload['selection']['max_tasks'] == max_tasks, 'same original prepared dispatch')
                _immutable(self.bucket, self._namespace(manifest) + '/mimo/dispatch.json', canonical(result))
                save_manifest(existing, result)
                return result
            population_path = self.root / 'POPULATION.json'
            if population_path.exists():
                population = signed(json.loads(population_path.read_bytes()), self.identity.id)
                _need(population['epoch'] == manifest['epoch'] and
                      population['manifest_sha256'] == sha(canonical(manifest)), 'original frozen population')
            else:
                captures = [json.loads(path.read_bytes())
                            for path in sorted((self.root / 'captured').glob('*.json'))]
                population = dict(version=VERSION, epoch=manifest['epoch'],
                    manifest_sha256=sha(canonical(manifest)), captures=captures, sealed_at=at)
                # Freeze before grading. A transient grader error cannot let a
                # later collection change the population selected on recovery.
                save_manifest(population_path, _signed(self.identity, population))
            selection = self.root / 'SELECTION.json'
            if selection.exists():
                policy = json.loads(selection.read_bytes())
                _need(policy['max_tasks'] == max_tasks, 'selection policy immutable on recovery')
            else:
                policy = dict(seed=secrets.token_hex(32), max_tasks=max_tasks)
                save_manifest(selection, policy)
            candidates, excluded = [], []
            # Fetch/authenticate only a bounded number of documents ahead when
            # the host supplies its process pool. The pool yields original input
            # order, so concurrency cannot change exclusions or seeded selection.
            def inputs():
                for envelope in population['captures']:
                    captured = signed(envelope, self.identity.id)
                    _need(captured['epoch'] == manifest['epoch'] and
                          captured['manifest_sha256'] == sha(canonical(manifest)), 'capture opening mismatch')
                    miner = captured['miner']
                    for item in captured['documents']:
                        from .complete_group_codec import limits, loads
                        data, _ = _get(self.bucket, item['key'], limits(manifest).metadata_bytes)
                        _need(sha(data) == item['sha256'], 'captured training input changed')
                        doc = loads(data, limits(manifest).metadata_bytes)
                        yield miner, item, doc['batch']
            from .audit_policy import InvalidSample
            def serial(requests, opening):
                for request in requests:
                    miner, _, batch = request
                    try:
                        grades = self.grade_batch(batch, opening, miner=miner)
                    except InvalidSample as error:
                        grades = error
                    yield request, grades
            graded = (self.grade_batches or serial)(inputs(), manifest)
            try:
                for (miner, item, batch), grades in graded:
                    # Only explicit InvalidSample excludes a claim. All worker,
                    # transport and native-infrastructure exceptions defer seal.
                    if isinstance(grades, InvalidSample):
                        excluded.append(dict(miner=miner, env_id=batch['env_id'], index=batch['index'],
                            document=item, batch_sha256=sha(canonical(batch)), native_grades=None,
                            assurance='native-claim-rejected-sampling-unaudited',
                            reason='native-claim-invalid', detail=str(grades)))
                        continue
                    _need(grades['batch_sha256'] == sha(canonical(batch)) and
                          grades['miner'] == miner and grades['sampling_verified'] is False and
                          grades['manifest_sha256'] == sha(canonical(manifest)),
                          'native admission must bind the exact unaudited batch')
                    results = grades['results']
                    _need(type(results) is list and len(results) == manifest['group_contract']['group_size'] and
                          all(type(row.get('nonce')) is int for row in results) and
                          [row['nonce'] for row in results] == list(range(len(results))),
                          'one native grade for every original attempt')
                    for row, original in zip(results, batch['rollouts']):
                        _need(row['classification'] in ('positive', 'negative', 'neutral') and
                              row['reward'] == float(row['classification'] == 'positive') and
                              row['output_sha256'] == sha(canonical(original['turns'][0]['output'])) and
                              row['stop_reason'] == original['turns'][0]['stop_reason'],
                              'complete native outcome and original token binding')
                    outcomes = Counter(row['classification'] for row in grades['results'])
                    group = manifest['group_contract']
                    reason = None
                    if outcomes['positive'] < group['min_success'] or outcomes['negative'] < group['min_completed_failure']:
                        reason = 'native-outcome-minima-not-met'
                    row = dict(miner=miner, env_id=batch['env_id'], index=batch['index'],
                        document=item, batch_sha256=grades['batch_sha256'],
                        native_grades=compact_native_grades(grades),
                        assurance='natively-graded-sampling-unaudited')
                    if reason:
                        excluded.append(dict(row, reason=reason))
                    else:
                        candidates.append(row)
            finally:
                # On validation failure do not leave an unfinished generator and
                # native subprocesses alive while the lifecycle retries.
                if hasattr(graded, 'close'):
                    graded.close()
            counts = Counter((r['env_id'], r['index']) for r in candidates)
            unique = []
            for row in candidates:
                if counts[(row['env_id'], row['index'])] > 1:
                    excluded.append(dict(row, reason='cross-miner-task-collision'))
                else:
                    unique.append(row)
            unique.sort(key=lambda row: sha(canonical([policy['seed'], row['miner'], row['env_id'], row['index']])))
            selected = unique[:max_tasks]
            excluded.extend(dict(row, reason='training-task-budget') for row in unique[max_tasks:])
            payload = dict(version=VERSION, epoch=manifest['epoch'], run_id=manifest['run_id'],
                checkpoint=manifest['checkpoint']['id'], manifest_sha256=sha(canonical(manifest)),
                population_sha256=sha(canonical(population)),
                selection=policy, selected=selected, excluded=excluded,
                training_requires_sampling_audit=False, selected_task_count=len(selected),
                selected_rollout_count=len(selected) * manifest['group_contract']['group_size'])
            result = _signed(self.identity, payload)
            _need(len(canonical(result)) <= 256 * 1024**2, 'bounded compact native dispatch')
            save_manifest(prepared, result)
            _immutable(self.bucket, self._namespace(manifest) + '/mimo/dispatch.json', canonical(result))
            save_manifest(existing, result)
            return result
        finally:
            os.close(fd)
