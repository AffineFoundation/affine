"""Authenticate host-prepared native groups for the isolated trainer worker."""
from pathlib import Path

from ..backend_jobs import signed
from ..complete_group_codec import limits, loads
from ..complete_group_native_receipts import expand_native_grades
from ..mimo_training_authenticity import ASSURANCE_VERIFIED
from .data import InputBinding, digest, sha
from .projection import project_document


def prepare_signed_dispatch(opening, dispatch, *, authority, documents_root,
                            runtime, optimizer_step=0, max_groups=None):
    """Verify host signatures and committed bytes, retaining every nonce.

    Compact documents are staged as <sha256>.json under documents_root. The
    signed native outcomes are generated by complete_group_native.grade_batch;
    this reader never fabricates a grade or treats a miner signature as a grade.
    max_groups narrows a private functional diagnostic, not a live selection.

    Train packs must set ``training_requires_sampling_audit=True`` and only
    include groups with sampling-verify ``verified_valid`` assurance. Unaudited
    and verify-fail groups are refused here (verified-or-nothing for GRPO).
    """
    manifest, selection = signed(opening, authority), signed(dispatch, authority)
    if (selection.get('version') != 'mimo-complete-group-coordinator-v1' or
            selection.get('epoch') != manifest['epoch'] or selection.get('run_id') != manifest['run_id'] or
            selection.get('checkpoint') != runtime.checkpoint_id or
            manifest['checkpoint']['id'] != runtime.checkpoint_id or
            selection.get('manifest_sha256') != digest(manifest) or
            selection.get('training_requires_sampling_audit') is not True):
        raise ValueError('authenticated train pack must require sampling authenticity')
    if manifest.get('mimo_runtime') != runtime.spec.to_dict():
        raise ValueError('authenticated opening must pin executed runtime')
    group_size = manifest['group_contract']['group_size']
    rows = selection['selected']
    if (type(rows) is not list or selection['selected_task_count'] != len(rows) or
            selection['selected_rollout_count'] != len(rows) * group_size):
        raise ValueError('nonempty complete task selection required')
    if max_groups is not None:
        if (type(max_groups) is not int or max_groups < 1 or
                not manifest['epoch'].startswith(('private-', 'test-', 'nonpayable-'))):
            raise ValueError('selection narrowing is private diagnostic only')
        rows = rows[:max_groups]
    root = Path(documents_root).resolve()
    bound = limits(manifest)
    binding = InputBinding(manifest['run_id'], manifest['epoch'], runtime.checkpoint_id,
        digest(manifest['group_contract']), optimizer_step)
    groups, receipts = [], []
    for row in rows:
        checksum = row['document']['sha256']
        if not sha(checksum):
            raise ValueError('original captured document hash')
        path = root/(checksum + '.json')
        if path.is_symlink() or not path.is_file() or path.stat().st_size > bound.metadata_bytes:
            raise ValueError('bounded ordinary original training document')
        document = loads(path.read_bytes(), bound.metadata_bytes)
        if digest(document) != checksum:
            raise ValueError('original captured document digest differs')
        grade = row['native_grades']
        batch = document['batch']
        if grade.get('version') == 'complete-group-native-grading-compact-v1':
            grade = expand_native_grades(grade, batch)
        # Native grades never claim sampling; authenticity is the train-pack
        # assurance + verified_valid sampling_audit_outcome from the ledger.
        if (grade.get('version') != 'complete-group-native-grading-v1' or
                grade.get('batch_sha256') != digest(batch) or row['batch_sha256'] != digest(batch) or
                grade.get('manifest_sha256') != digest(manifest) or grade.get('miner') != row['miner'] or
                grade.get('sampling_verified') is not False or
                row.get('assurance') != ASSURANCE_VERIFIED or
                row.get('sampling_audit_outcome') != 'verified_valid' or
                row['env_id'] != batch['env_id'] or row['index'] != batch['index']):
            raise ValueError('host native grading must bind committed original task and sampling-verified train pack')
        group, receipt = project_document(document, expected_document_sha256=checksum,
            binding=binding, trusted_prompt=grade['prompt'], native_results=grade['results'],
            vocab_size=runtime.vocab_size, eos_token_ids=runtime.eos_token_ids, group_size=group_size)
        groups.append(group)
        receipts.append(receipt)
    if len({g.task_id for g in groups}) != len(groups):
        raise ValueError('distinct native tasks per optimizer update')
    return dict(manifest=manifest, dispatch=selection, binding=binding,
        groups=tuple(groups), receipts=receipts,
        diagnostic_omitted_groups=len(selection['selected']) - len(groups))
